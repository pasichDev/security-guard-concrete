    public static function guess(string $ip): string
    {
        $ip = IpRange::normalize($ip);
        if ($ip === '' || strpos($ip, ':') !== false) {
            return '';
        }
        $parts = explode('.', $ip);
        if (count($parts) !== 4) {
            return '';
        }
        foreach ([3, 2, 1] as $n) {
            $prefix = implode('.', array_slice($parts, 0, $n)) . '.';
            if (isset(self::PREFIXES[$prefix])) {
                return self::PREFIXES[$prefix];
            }
        }

        return '';
    }

    /** Розбирає geo_block_countries ("RU, CN by") у список ISO-кодів у верхньому регістрі. */
    public static function parseCountries(string $value): array
    {
        $out = [];
        foreach (preg_split('/[\s,;]+/', strtoupper($value)) ?: [] as $code) {
            if (preg_match('/^[A-Z]{2}$/', $code)) {
                $out[$code] = true;
            }
        }

        return array_keys($out);
    }
